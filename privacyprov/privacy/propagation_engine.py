    def _initial_annotation_counter(self) -> int:
        count = 0
        for node in self.graph.nodes.values():
            if node.label == "PrivacyAnnotation":
                count += 1
        return count

    def _count_privacy_annotations(self) -> int:
        return len([n for n in self.graph.nodes.values() if n.label == "PrivacyAnnotation"])

    def _propagated_annotation_counts(self) -> Dict[str, int]:
        total = 0
        by_target: Dict[str, int] = {}
        for node in self.graph.nodes.values():
            if node.label != "PrivacyAnnotation":
                continue
            source = str(node.props.get("source", ""))
            if not source.startswith("propagated"):
                continue
            total += 1
            label = str(node.props.get("target_label", "unknown"))
            by_target[f"propagated_{label}_annotations"] = by_target.get(f"propagated_{label}_annotations", 0) + 1
        by_target["propagated_annotations_total"] = total
        return by_target

    def _step_runs_in_order(self) -> List[Node]:
        step_runs = [n for n in self.graph.nodes.values() if n.label == "StepRun"]

        def order_key(node: Node) -> Tuple[int, str]:
            parts = node.key.split("::")
            for part in parts:
                if part.isdigit():
                    return (int(part), node.key)
            return (999999, node.key)

        return sorted(step_runs, key=order_key)

    def _input_artifacts(self, step_run: Node, policy: OperationPolicySpec) -> List[Node]:
        return self._artifacts_from_rel(step_run, "used", direction="out", fallback_ids=policy.inputArtifacts)

    def _output_artifacts(self, step_run: Node, policy: OperationPolicySpec) -> List[Node]:
        return self._artifacts_from_rel(step_run, "wasGeneratedBy", direction="in", fallback_ids=policy.outputArtifacts)

    def _artifacts_from_rel(
        self,
        step_run: Node,
        rel_type: str,
        *,
        direction: str,
        fallback_ids: Sequence[str],
    ) -> List[Node]:
        nodes: List[Node] = []
        for rel in self.graph.relationships:
            if rel.rel_type != rel_type:
                continue
            if direction == "out" and rel.start_label == "StepRun" and rel.start_key == step_run.key:
                node = self.graph.nodes.get((rel.end_label, rel.end_key))
                if node is not None and node.label in ARTIFACT_LABELS:
                    nodes.append(node)
            elif direction == "in" and rel.end_label == "StepRun" and rel.end_key == step_run.key:
                node = self.graph.nodes.get((rel.start_label, rel.start_key))
                if node is not None and node.label in ARTIFACT_LABELS:
                    nodes.append(node)
        if not nodes:
            for artifact_id in fallback_ids:
                node = self._find_artifact(artifact_id)
                if node is not None:
                    nodes.append(node)
        return nodes

    def _find_artifact(self, artifact_id: str) -> Optional[Node]:
        for label in ARTIFACT_LABELS:
            node = self.graph.nodes.get((label, str(artifact_id)))
            if node is not None:
                return node
        return None

    def _records_for_dataset(self, dataset_id: str) -> List[Node]:
        records: List[Node] = []
        for rel in self.graph.relationships:
            if rel.rel_type == "containsDR" and rel.start_label == "DatasetArtifact" and rel.start_key == dataset_id:
                node = self.graph.nodes.get((rel.end_label, rel.end_key))
                if node is not None:
                    records.append(node)
        return records

    def _cells_for_dataset(self, dataset_id: str) -> List[Node]:
        return [
            n for n in self.graph.nodes.values()
            if n.label == "DataCellArtifact" and n.props.get("dataset_id") == dataset_id
        ]

    def _cells_for_record(self, record_key: str) -> List[Node]:
        cells: List[Node] = []
        for rel in self.graph.relationships:
            if rel.rel_type == "containsRC" and rel.start_label == "DataRecordArtifact" and rel.start_key == record_key:
                node = self.graph.nodes.get((rel.end_label, rel.end_key))
                if node is not None:
                    cells.append(node)
        return cells

    def _matching_input_cells(self, input_dataset_id: str, out_cell: Node, source_attribute: str) -> List[Node]:
        record_id = str(out_cell.props.get("record_id"))
        candidate_key = f"{input_dataset_id}::record::{record_id}::cell::{source_attribute}"
        node = self.graph.nodes.get(("DataCellArtifact", candidate_key))
        if node is not None:
            return [node]
        # Fallback: search by dataset, record_id, and attribute in case key policy changes.
        matches: List[Node] = []
        for n in self.graph.nodes.values():
            if n.label != "DataCellArtifact":
                continue
            if (
                n.props.get("dataset_id") == input_dataset_id
                and str(n.props.get("record_id")) == record_id
                and str(n.props.get("attribute")) == str(source_attribute)
            ):
                matches.append(n)
        return matches

    def _granularity_for_label(self, label: str) -> str:
        return {
            "DatasetArtifact": "dataset",
            "DataRecordArtifact": "record",
            "DataCellArtifact": "cell",
            "ModelArtifact": "model",
            "EvaluationMetric": "metric",
        }.get(label, "artifact")
